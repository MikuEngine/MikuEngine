#pragma once

namespace game
{
    // ═══════════════════════════════════════════════════════════════
    // BulletType - 총알 이동 방식 열거형
    // ═══════════════════════════════════════════════════════════════
    enum class BulletType
    {
        BulletPlayer,   // 플레이어 전용(기본 직선이동)
        Linear,         // 직선 이동
        Parabolic,      // 포물선 (곡사)
        Curve,          // 곡선용
		Field,          // 범위형
		// Spiral,      // 나선형
        // Homing,      // 유도
    };

    // ═══════════════════════════════════════════════════════════════
    // BulletParams - 총알 생성 파라미터
    // 
    // 호출자가 Factory에 전달하는 "요청서"
    // Factory는 이 정보를 바탕으로 총알을 생성하고 초기화
    // 
    // 참고:
    //   - 수명, 데미지 등은 발사하는 쪽(플레이어/몬스터)에서 관리
    //   - 이 구조체는 이동 방식과 속도만 전달
    // ═══════════════════════════════════════════════════════════════
    struct BulletParams
    {
        // ─────────────────────────────────────────────
        // 이동 방식
        // ─────────────────────────────────────────────
        BulletType type = BulletType::Linear;

        // ─────────────────────────────────────────────
        // 공통 속성
        // ─────────────────────────────────────────────
        float speed = 10.0f;        // 총알 속도
        float lifetime = 3.0f;      // 총알 수명 (초) - BulletPlayer는 range 사용, 다른 타입은 lifetime 사용
        float range = 50.0f;         // 총알 사거리 (BulletPlayer 전용, lifetime 대신 사용)
        float damage = 0.0f;

        // ─────────────────────────────────────────────
        // 포물선용 (Parabolic 타입에서만 사용)
        // - 다른 타입에서는 이 값들을 무시함
        // ─────────────────────────────────────────────
        float launchAngle = 45.0f;  // 발사 상방 각도 (0~89도)
        float ownGravity = 9.8f;    // 자체 중력 가속도 (PhysX 글로벌 중력과 별개)

        // ─────────────────────────────────────────────
        // 곡선/나선용 (Curve 타입에서 사용)
        // ─────────────────────────────────────────────
        float curveSpeed = 0.0f;        // [미사용] 기존 곡선 속도
        float angularSpeed = 2.0f;      // 회전 속도 (rad/s)
        float radiusGrowthRate = 1.0f;  // 반지름 증가율 (m/s)

        // ─────────────────────────────────────────────
        // 범위형
        // ─────────────────────────────────────────────
        float radius = 3.0f;        // 충돌 반경

        // ─────────────────────────────────────────────
        // 나선용
        // ─────────────────────────────────────────────
        // float spiralFrequency = 2.0f;

        // ─────────────────────────────────────────────
        // 유도용 (추후 구현)
        // ─────────────────────────────────────────────
        // GameObject* target = nullptr;
        // float turnSpeed = 5.0f;
    };
}
